import XCTest
@testable import Assinafy

final class PayloadDocumentationTests: XCTestCase {
    func testResponseExamplesDecodeWithSDKModels() throws {
        let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
            .deletingLastPathComponent().deletingLastPathComponent()
        let source = try String(contentsOf: root.appendingPathComponent("docs/PAYLOADS.md"), encoding: .utf8)
        let pattern = try NSRegularExpression(pattern: "### ([A-Za-z][A-Za-z0-9-]*)\\n(?:(?!\\n### )[\\s\\S])*?```json\\n([\\s\\S]*?)\\n```")
        let examples = Dictionary(uniqueKeysWithValues: pattern.matches(in: source, range: NSRange(source.startIndex..., in: source)).map {
            (String(source[Range($0.range(at: 1), in: source)!]), Data(source[Range($0.range(at: 2), in: source)!].utf8))
        })
        func decode<T: Decodable>(_ name: String, as type: T.Type) throws {
            let data = try XCTUnwrap(examples[name], "Missing \(name) payload")
            XCTAssertNoThrow(try JSONDecoder.assinafy.decode(type, from: data), "\(name) payload")
        }
        for name in ["DocumentContract", "DocumentContractRenewed", "DocumentContractTerminated"] {
            try decode(name, as: DocumentContract.self)
        }
        for name in ["DocumentContractAmendment", "DocumentContractAmendmentApplied"] {
            try decode(name, as: DocumentContractAmendment.self)
        }
        let contract = try JSONDecoder.assinafy.decode(ContractDetails.self, from: XCTUnwrap(examples["DocumentContract"]))
        XCTAssertEqual(contract.contract?.value, NSDecimalNumber(string: "1300"))
        XCTAssertNotNil(contract.contract?.document)
        XCTAssertEqual(contract.contract?.amendments.count, 1)
        XCTAssertNil(contract.amendment)
        let amendment = try JSONDecoder.assinafy.decode(ContractDetails.self, from: XCTUnwrap(examples["DocumentContractAmendment"]))
        XCTAssertEqual(amendment.amendment?.relationType, "amendment")
        XCTAssertNotNil(amendment.amendment?.termsJSON)
        XCTAssertNil(amendment.contract)
        try decode("IdentityVerificationState", as: IdentityVerificationState.self)
        try decode("IdentityVerificationSession", as: IdentityVerificationSession.self)
        try decode("SignerIdentityReview", as: SignerIdentityReview.self)
        try decode("CreatedWebhookEndpoint", as: WebhookEndpoint.self)
        let review = try JSONDecoder.assinafy.decode(SignerIdentityReview.self, from: XCTUnwrap(examples["SignerIdentityReview"]))
        XCTAssertEqual(review.expected?.cpf, "00000000000")
        XCTAssertEqual(review.document?.type, "CNH")
        XCTAssertEqual(review.matches?.cpf?.boolValue, true)
        XCTAssertEqual(review.matches?.name?.doubleValue, 0.52)
        XCTAssertNil(review.matches?.birthDate)
        XCTAssertEqual(review.reasonCodes.first?.reasonDescription, "Name requires review")
        XCTAssertEqual(review.checks.first?.reasons, ["NAME_MISMATCH"])
        XCTAssertEqual(review.checks.first?.score?.doubleValue, 0.52)
        XCTAssertEqual(review.images, ["document_front", "document_back", "face"])
        let endpoint = try JSONDecoder.assinafy.decode(WebhookEndpoint.self, from: XCTUnwrap(examples["CreatedWebhookEndpoint"]))
        XCTAssertNotNil(endpoint.secret)
        XCTAssertFalse(endpoint.isHeld)
        XCTAssertNil(endpoint.heldSince)
        try decode("response-9", as: OAuthTokenResponse.self)
        try decode("response-10", as: OAuthUserInfo.self)
        try decode("response-18", as: OAuthProtectedResourceMetadata.self)
        try decode("AuthUser", as: User.self)
        try decode("AuthAccount", as: Account.self)
        try decode("AuthSession", as: LoginResponse.self)
        try decode("Signer", as: Signer.self)
        try decode("SignerSelf", as: SignerSelfInfo.self)
        try decode("DocumentPage", as: DocumentPage.self)
        try decode("DisplaySettings", as: DisplaySettings.self)
        try decode("DocumentStatus", as: DocumentStatusInfo.self)
        try decode("Document", as: DocumentDetails.self)
        try decode("Document", as: DocumentListItem.self)
        try decode("Document", as: DocumentUploadResponse.self)
        try decode("Document", as: PublicDocumentInfo.self)
        let document = try JSONDecoder.assinafy.decode(DocumentDetails.self, from: XCTUnwrap(examples["Document"]))
        XCTAssertEqual(document.verificationCode, "verification_example_001")
        XCTAssertEqual(document.verificationURL, "https://app.example.invalid/verify/verification_example_001")
        XCTAssertEqual(document.hasContract?.boolValue, false)
        XCTAssertEqual(document.currentSigner?.id, "id_example_001")
        XCTAssertEqual(document.assignment?.documentId, "id_example_001")
        try decode("Account", as: WorkspaceResponse.self)
        let account = try JSONDecoder.assinafy.decode(WorkspaceResponse.self, from: XCTUnwrap(examples["Account"]))
        XCTAssertEqual(account.limits?.webhookEndpoints?.intValue, 3)
        try decode("AccountTheme", as: AccountTheme.self)
        try decode("Field", as: FieldDefinition.self)
        try decode("Tag", as: Tag.self)
        try decode("SigningUrl", as: AssignmentSigningURL.self)
        try decode("AssignmentSigner", as: Signer.self)
        try decode("AssignmentItem", as: AssignmentItem.self)
        try decode("AssignmentSummary", as: AssignmentSummary.self)
        try decode("Assignment", as: Assignment.self)
        let assignment = try JSONDecoder.assinafy.decode(Assignment.self, from: XCTUnwrap(examples["Assignment"]))
        XCTAssertEqual(assignment.documentId, "document_example_001")
        XCTAssertEqual(assignment.createdAt, "2099-01-01T12:00:00Z")
        try decode("CostEstimate", as: CostEstimate.self)
        let reminder = try JSONDecoder.assinafy.decode(CostEstimate.self, from: XCTUnwrap(examples["ResendCostEstimate"]))
        XCTAssertEqual(reminder.totalCredits, 0.45)
        XCTAssertTrue(reminder.hasSufficientResources)
        XCTAssertTrue(reminder.hasSufficientBalance)
        XCTAssertTrue(reminder.raw["credit_balance"] is NSNull)
        XCTAssertEqual(reminder.breakdown.first?.cost, 0.45)
        try decode("TemplateFieldPlacement", as: TemplateFieldPlacement.self)
        try decode("TemplatePage", as: TemplatePage.self)
        try decode("TemplateRole", as: TemplateRole.self)
        try decode("Template", as: TemplateDetails.self)
        try decode("WebhookSubscription", as: WebhookSubscription.self)
        try decode("WebhookDispatch", as: WebhookDispatch.self)
        let dispatch = try JSONDecoder.assinafy.decode(WebhookDispatch.self, from: XCTUnwrap(examples["WebhookDispatch"]))
        XCTAssertEqual(dispatch.webhookId, "delivery_example_001")
        XCTAssertEqual(dispatch.attempt?.intValue, 2)
        XCTAssertEqual(dispatch.kind, "scheduled")
        XCTAssertFalse(dispatch.willRetry)
        XCTAssertEqual(dispatch.httpStatusCode?.intValue, 200)
        try decode("WebhookEventType", as: WebhookEventTypeInfo.self)
        try decode("FieldType", as: FieldTypeInfo.self)
        try decode("FieldValidationResult", as: FieldValidationResult.self)
        try decode("DocumentVerification", as: DocumentVerification.self)
        try decode("SendToken", as: SendTokenResponse.self)
        try decode("DocumentActivity", as: DocumentActivity.self)
        try decode("WhatsappNotification", as: WhatsappNotification.self)
        let notification = try JSONDecoder.assinafy.decode(WhatsappNotification.self, from: XCTUnwrap(examples["WhatsappNotification"]))
        XCTAssertEqual(notification.sentAtString, "2099-01-01T12:00:00Z")
        XCTAssertGreaterThan(notification.sentAt, 0)
        try decode("DocumentStatsRow", as: DocumentStatsRow.self)
        try decode("NotificationPreferences", as: NotificationPreferences.self)
        let preferences = try JSONDecoder.assinafy.decode(NotificationPreferences.self, from: XCTUnwrap(examples["NotificationPreferences"]))
        XCTAssertTrue(preferences.contractRenewalNotice)
        XCTAssertTrue(preferences.contractExpiring)
        XCTAssertTrue(preferences.contractExpired)
        XCTAssertTrue(preferences.contractRenewed)
        try decode("WebhookEndpoint", as: WebhookEndpoint.self)
        try decode("WebhookSigningSecret", as: WebhookSigningSecret.self)
        try decode("MFAStatus", as: MFAStatus.self)
        try decode("TOTPEnrollment", as: TOTPEnrollment.self)
        try decode("RecoveryCodes", as: MFARecoveryCodes.self)
        XCTAssertThrowsError(
            try JSONDecoder.assinafy.decode(LoginResponse.self, from: XCTUnwrap(examples["MFAChallenge"]))
        ) { XCTAssertEqual(($0 as? MFARequiredError)?.mfaToken, "mfa_token_example_001") }
    }
}
